"""Regenerate the numeric snapshot in README.md from the code.

    uv run python -m tools.suite_stats --write

The snapshot is the only place the README states task counts, cheat counts,
the judge's share of a task score, library test totals, and the assumption-based
cost. Do not type those numbers by hand. ``tests/test_suite_stats.py`` fails
if the committed snapshot drifts from this output.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

from graders.scoring import PRIMARY_WEIGHT, RUBRIC_WEIGHT
from harness.config import run_config
from harness.paths import REPO, TARGET
from harness.task import CATEGORY_PREFIX, discover_tasks
from tools.estimate_cost import assumption_breakdown
from validation.validate_tasks import planted_cheats

README = REPO / "README.md"
START, END = "<!-- SUITE:START -->", "<!-- SUITE:END -->"
CATEGORIES = list(CATEGORY_PREFIX)


def _collect_pytest(root: Path) -> int:
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "pytest",
            "--collect-only",
            "-q",
            "-p",
            "no:cacheprovider",
            "-o",
            "addopts=",
        ],
        cwd=root,
        capture_output=True,
        text=True,
    )
    match = re.search(r"(\d+) tests collected", result.stdout)
    if result.returncode not in (0, 5) or match is None:
        raise RuntimeError(f"could not collect tests in {root}:\n{result.stdout[-500:]}\n{result.stderr[-500:]}")
    return int(match.group(1))


def _collect_vitest(root: Path) -> int:
    """Count tests vitest actually runs, including rows expanded from `it.each`."""
    binary = root / "node_modules" / ".bin" / "vitest"
    if not binary.is_file():
        raise RuntimeError(f"{binary} is missing; run npm ci in {root}")
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "vitest.json"
        result = subprocess.run(
            [str(binary), "run", "--reporter=json", f"--outputFile={out}"],
            cwd=root,
            capture_output=True,
            text=True,
        )
        if result.returncode != 0 or not out.is_file():
            raise RuntimeError(f"vitest run failed in {root}:\n{result.stdout[-400:]}\n{result.stderr[-400:]}")
        return int(json.loads(out.read_text(encoding="utf-8"))["numTotalTests"])


def _pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def _money(value: float) -> str:
    return f"${value:,.2f}"


def snapshot_data() -> dict:
    tasks = discover_tasks()
    by_cat = Counter(t.category for t in tasks)
    by_lang = Counter(t.language for t in tasks)
    by_diff = Counter(t.difficulty for t in tasks)
    flawed = sum(len(t.flawed) for t in tasks)
    upstream = [t for t in tasks if t.source and t.source.upstream]
    synthetic_pr = [
        t for t in tasks if t.category == "pr_derived" and not (t.source and t.source.upstream)
    ]
    generic = specific = 0
    for task in tasks:
        for name in planted_cheats(task):
            if name.startswith("patch:"):
                specific += 1
            else:
                generic += 1
    shares = []
    judge_items = auto_items = 0
    for task in tasks:
        total = sum(item.weight for item in task.rubric)
        judge = sum(item.weight for item in task.rubric if item.grader == "judge")
        shares.append(RUBRIC_WEIGHT * judge / total)
        judge_items += sum(item.grader == "judge" for item in task.rubric)
        auto_items += sum(item.grader == "auto" for item in task.rubric)
    history = {
        lib.name: len(list((TARGET / "history" / lib.name).glob("*.patch")))
        for lib in (TARGET / "history").iterdir()
        if lib.is_dir()
    }
    tests = {
        "shopcore": _collect_pytest(TARGET / "shopcore"),
        "ledgerkit": _collect_vitest(TARGET / "ledgerkit"),
        "more-itertools": _collect_pytest(TARGET / "more-itertools"),
    }
    cfg = run_config()
    cost = assumption_breakdown(len(tasks), cfg.k, 25, 3_000, 25_000, 1_500, 2.0)
    return {
        "tasks": tasks,
        "by_cat": by_cat,
        "by_lang": by_lang,
        "by_diff": by_diff,
        "flawed": flawed,
        "upstream": upstream,
        "synthetic_pr": synthetic_pr,
        "generic": generic,
        "specific": specific,
        "shares": shares,
        "judge_items": judge_items,
        "auto_items": auto_items,
        "history": history,
        "tests": tests,
        "cost": cost,
    }


def render_snapshot(data: dict | None = None) -> str:
    data = data or snapshot_data()
    tasks = data["tasks"]
    n = len(tasks)
    shares = data["shares"]
    lines = [
        "Generated by `uv run python -m tools.suite_stats --write` from the task files, the target suites, and",
        "`tools/estimate_cost.py`. Do not edit by hand.",
        "",
        f"**{n} tasks.** {data['by_lang']['python']} Python, {data['by_lang']['typescript']} TypeScript.",
        "",
        "| Category | Python | TypeScript | Total |",
        "| --- | --- | --- | --- |",
    ]
    for category in CATEGORIES:
        py = sum(t.category == category and t.language == "python" for t in tasks)
        ts = sum(t.category == category and t.language == "typescript" for t in tasks)
        lines.append(f"| {category} | {py} | {ts} | {py + ts} |")
    lines += [
        "",
        "| Difficulty | Tasks | Share |",
        "| --- | --- | --- |",
    ]
    for difficulty in ("easy", "medium", "hard"):
        count = data["by_diff"][difficulty]
        lines.append(f"| {difficulty} | {count} | {count / n:.0%} |")
    lines += [
        "",
        f"Flawed solutions on disk: **{data['flawed']}**.",
        "",
        f"Planted cheats: **{data['generic'] + data['specific']}**. "
        f"**{data['generic']}** are the generic ones `validation/validate_tasks.py` builds for each task "
        f"(delete a test file, delete one test when the file has a top-level test function, add a skip, "
        f"read the hidden tests, run a network command). **{data['specific']}** are task files under `cheats/`. "
        "Validation must catch every one of them. The generic checks are the same five ideas repeated, "
        "not 200 distinct attacks.",
        "",
        f"PR-derived tasks: **{len(data['synthetic_pr'])}** from the shopcore and ledgerkit history I wrote, "
        f"**{len(data['upstream'])}** from an upstream project "
        f"({', '.join(t.id for t in data['upstream']) or 'none yet'}).",
        "",
        "History commits stored as patches: "
        + ", ".join(f"{lib} {data['history'][lib]}" for lib in sorted(data["history"]))
        + f", **{sum(data['history'].values())}** in total. "
        "Rebuilding that history is checked by `make validate` and `tests/test_target_history.py`.",
        "",
        "Tests in the target trees, counted by collecting them, not by hand:",
        "",
        "| Tree | Collected tests |",
        "| --- | --- |",
    ]
    for name, count in data["tests"].items():
        lines.append(f"| {name} | {count} |")
    mean = sum(shares) / len(shares)
    lines += [
        "",
        f"Score weights in `graders/scoring.py`: primary **{PRIMARY_WEIGHT:.1f}**, rubric **{RUBRIC_WEIGHT:.1f}**. "
        "The rubric weight is split between auto checks and the LLM judge in proportion to item weights. "
        f"Across {n} tasks the judge's share of the task score, when the primary passes and the penalty is zero, "
        f"is **{_pct(min(shares))}** minimum, **{_pct(mean)}** average, **{_pct(max(shares))}** maximum. "
        f"There are {data['judge_items']} judge items and {data['auto_items']} auto items. "
        "The judge does not decide the whole rubric weight.",
        "",
        "Assumption-based cost of one full paid run, from `tools/estimate_cost.py` "
        f"({data['cost']['n_tasks']} tasks x k={data['cost']['k']}, "
        f"{data['cost']['steps']} steps, {data['cost']['fresh_in']} uncached + {data['cost']['cached_in']} cached "
        f"input tokens and {data['cost']['out']} output tokens per step, "
        f"{data['cost']['judge_items']:.0f} judge items per episode). "
        "These are assumptions. `make estimate` prints the same total. A smoke test replaces them.",
        "",
        "| Participant | $/episode | Episodes | Subtotal |",
        "| --- | --- | --- | --- |",
    ]
    for row in data["cost"]["rows"]:
        lines.append(
            f"| {row['name']} | {row['per_episode']:.2f} | {row['episodes']} | {_money(row['cost'])} |"
        )
    lines.append(f"| judging | | {data['cost']['judge_episodes']} | {_money(data['cost']['judging'])} |")
    lines.append(f"| **total** | | | **{_money(data['cost']['total'])}** |")
    return "\n".join(lines)


def write_readme(snapshot: str | None = None) -> None:
    snapshot = snapshot if snapshot is not None else render_snapshot()
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"{README} is missing {START} / {END} markers")
    head, _, rest = text.partition(START)
    _, _, tail = rest.partition(END)
    README.write_text(f"{head}{START}\n{snapshot}\n{END}{tail}", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="replace the README snapshot")
    args = parser.parse_args(argv)
    snapshot = render_snapshot()
    if args.write:
        write_readme(snapshot)
        print(f"updated {README.relative_to(REPO)}")
    else:
        print(snapshot)
    return 0


if __name__ == "__main__":
    sys.exit(main())
