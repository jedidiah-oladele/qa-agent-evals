"""Write docs/tasks.md: every task in one table, plus the category/language/difficulty spread.

    uv run python -m tools.task_catalog
"""

from __future__ import annotations

import sys
from collections import Counter

from harness.paths import REPO, TASKS
from harness.task import CATEGORY_PREFIX, discover_tasks
from harness.workspace import hidden_test_paths

OUT = REPO / "docs" / "tasks.md"
CATEGORIES = list(CATEGORY_PREFIX)


def primary_summary(task) -> str:
    p = task.primary
    if p.type == "hidden_tests":
        return f"{len(p.fail_to_pass)} fail-to-pass tests + pass-to-pass"
    if p.type == "mutation":
        return f"kill >= {p.min_mutant_kill_rate:.0%} of {len(task.mutants)} mutants"
    if p.type == "repeated_runs":
        return f"{p.runs} shuffled/perturbed runs green"
    return f"{len(p.defects)} seeded defect(s), <= {p.max_false_positives} false positives"


def main() -> int:
    tasks = discover_tasks(TASKS)
    lines = [
        "# Task catalog",
        "",
        "Generated by `uv run python -m tools.task_catalog` from `tasks/*/task.yaml`. Do not edit by hand.",
        "",
        f"**{len(tasks)} tasks.**",
        "",
        "| Category | Python | TypeScript | Total |",
        "| --- | --- | --- | --- |",
    ]
    for c in CATEGORIES:
        py = sum(t.category == c and t.language == "python" for t in tasks)
        ts = sum(t.category == c and t.language == "typescript" for t in tasks)
        lines.append(f"| {c} | {py} | {ts} | {py + ts} |")
    py = sum(t.language == "python" for t in tasks)
    lines.append(f"| **all** | {py} | {len(tasks) - py} | {len(tasks)} |")
    diff = Counter(t.difficulty for t in tasks)
    lines += ["", "| Difficulty | Tasks | Share |", "| --- | --- | --- |"]
    for d in ("easy", "medium", "hard"):
        lines.append(f"| {d} | {diff[d]} | {diff[d] / max(1, len(tasks)):.0%} |")
    lines += ["", "| Task | Category | Language | Difficulty | Title | Primary grader | Flawed | Hidden test files |",
              "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for t in tasks:
        lines.append(f"| [`{t.id}`](../tasks/{t.id}/task.yaml) | {t.category} | {t.language} | {t.difficulty} | "
                     f"{t.title} | {primary_summary(t)} | {len(t.flawed)} | {len(hidden_test_paths(t))} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(tasks)} tasks)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
