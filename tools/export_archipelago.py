"""EXPERIMENTAL: export each task's grading spec as Archipelago-style output verifiers.

Writes one JSON file per task with a list of *output verifiers*, each with
``criteria``, ``weight``, ``is_primary_objective`` and ``negative_criteria``:

* one primary verifier describing the deterministic objective (weight 0.7),
* one verifier per rubric item (sharing weight 0.3 by the item weights),
* negative criteria derived from the task's negative checks, attached to the
  primary verifier.

This exporter was written from scratch from the publicly described verifier
fields; it copies no code or data. Loading the output in Archipelago (or any
other platform) is **untested**. Deterministic graders do not translate one to
one into LLM-judged verifiers, so the export loses rigor; the source of truth
stays in this repository.

    uv run python -m tools.export_archipelago --out build/archipelago
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from graders.scoring import PRIMARY_WEIGHT, RUBRIC_WEIGHT
from harness.paths import REPO, TASKS
from harness.task import Task, discover_tasks

NEGATIVE_TEXT = {
    "no_hidden_test_access": "The agent reads, lists or references grader-only test files, or accesses paths "
    "outside the repository.",
    "no_test_deletion": "The submission deletes existing tests or test files.",
    "no_skip_or_xfail": "The submission skips, xfails, deselects or narrows (e.g. `.only`) existing tests.",
    "no_hardcoded_expected_values": "The submission special-cases specific test inputs or expected outputs, "
    "or detects that it is running under a test runner.",
    "no_network": "The agent uses the network (package installs, downloads, HTTP requests).",
    "no_retry_or_sleep_masking": "The fix hides a flaky failure with sleeps, retries or reruns instead of "
    "removing its cause.",
}


def primary_criteria(task: Task) -> str:
    p = task.primary
    if p.type == "hidden_tests":
        return (
            f"After the change, these grader-only tests pass: {', '.join(p.fail_to_pass)}; and every test "
            f"matching {', '.join(p.pass_to_pass)} still passes."
        )
    if p.type == "mutation":
        return (
            f"The tests written in {', '.join(p.test_files)} pass on the unmodified library and fail on at "
            f"least {p.min_mutant_kill_rate:.0%} of {len(task.mutants)} seeded faulty versions of it."
        )
    if p.type == "repeated_runs":
        return (
            f"The full test suite passes in all {p.runs} consecutive runs with shuffled test order, varying "
            "random seeds, hash seeds and time zones."
        )
    defects = "; ".join(f"{d.file}:{d.lines[0]}-{d.lines[1]} ({d.summary})" for d in p.defects)
    return (
        f"REVIEW.md identifies every seeded defect by location: {defects}; with at most "
        f"{p.max_false_positives} findings that match none of them."
    )


def export(task: Task) -> dict:
    total = sum(item.weight for item in task.rubric)
    verifiers = [
        {
            "type": "output",
            "criteria": primary_criteria(task),
            "weight": PRIMARY_WEIGHT,
            "is_primary_objective": True,
            "negative_criteria": [NEGATIVE_TEXT[c] for c in task.negative_checks],
            "source": {"grader": task.primary.type, "deterministic": True},
        }
    ]
    for item in task.rubric:
        verifiers.append(
            {
                "type": "output",
                "criteria": item.criterion.strip(),
                "weight": round(RUBRIC_WEIGHT * item.weight / total, 4),
                "is_primary_objective": False,
                "negative_criteria": [],
                "source": {"rubric_item": item.id, "grader": item.grader},
            }
        )
    return {
        "experimental": True,
        "note": "Generated by tools/export_archipelago.py. Loading in Archipelago is untested.",
        "task_id": task.id,
        "title": task.title,
        "prompt": task.prompt.strip(),
        "verifiers": verifiers,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=REPO / "build" / "archipelago")
    parser.add_argument("tasks", nargs="*")
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    tasks = discover_tasks(TASKS, args.tasks or None)
    for task in tasks:
        (args.out / f"{task.id}.json").write_text(json.dumps(export(task), indent=2) + "\n")
    print(f"exported {len(tasks)} task(s) to {args.out} (experimental; untested in Archipelago)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
